// @vitest-environment jsdom
import { act } from 'react';
import { createRoot } from 'react-dom/client';
import { afterEach, expect, it, vi } from 'vitest';
import { useCodexPictures } from './codexPictures';
import { createMemoryStoryCoverStore } from './storyCovers';
import type { CodexPictureService } from '@seihouse/library/stories';

(globalThis as { IS_REACT_ACT_ENVIRONMENT?: boolean }).IS_REACT_ACT_ENVIRONMENT = true;
const roots: Array<ReturnType<typeof createRoot>> = [];
afterEach(async () => { for (const root of roots.splice(0)) await act(async () => root.unmount()); vi.restoreAllMocks(); });
const request = { card: { name: 'Lin Wei', subject: 'character' as const, look: { summary: 'A young man with black hair.', traits: {} } }, story: {} };
async function mount(store = createMemoryStoryCoverStore(), maker = vi.fn(async () => new Blob(['portrait'], { type: 'image/png' }))) {
  Object.assign(URL, { createObjectURL: vi.fn(() => `blob:${Math.random()}`), revokeObjectURL: vi.fn() });
  let service: CodexPictureService;
  function Host() { service = useCodexPictures(store, maker); return null; }
  const root = createRoot(document.createElement('div')); roots.push(root);
  await act(async () => root.render(<Host />));
  return { current: () => service!, maker };
}

it('restores the saved bytes and prepares a real image attachment after reload', async () => {
  const store = createMemoryStoryCoverStore();
  const image = new Blob(['portrait'], { type: 'image/png' });
  await store.save('story/lin', image);
  const host = await mount(store);
  expect(await host.current().imageOf('story', 'lin')).toBe(image);
  expect(host.current().pictureOf('story', 'lin')).toMatch(/^blob:/);
  expect(await host.current().referenceOf('story', 'lin')).toEqual({ data: btoa('portrait'), mimeType: 'image/png' });
});

it('coalesces duplicate manifestation requests and saves one image', async () => {
  const store = createMemoryStoryCoverStore();
  const host = await mount(store);
  await act(async () => {
    const first = host.current().manifest('story', 'lin', request);
    expect(host.current().manifest('story', 'lin', request)).toBe(first);
    await first;
  });
  expect(host.maker).toHaveBeenCalledTimes(1);
  expect(await store.loadAll()).toHaveLength(1);
});

it('preserves the old portrait after a failed save and retries the generated bytes for free', async () => {
  const store = createMemoryStoryCoverStore();
  const old = new Blob(['old'], { type: 'image/png' });
  await store.save('story/lin', old);
  const host = await mount(store);
  const save = vi.spyOn(store, 'save').mockRejectedValueOnce(new Error('Device full'));
  const previous = host.current().pictureOf('story', 'lin');
  await act(async () => { await expect(host.current().manifest('story', 'lin', request)).rejects.toThrow('Device full'); });
  expect(host.current().pictureOf('story', 'lin')).toBe(previous);
  expect(await host.current().imageOf('story', 'lin')).toBe(old);
  await act(async () => { await host.current().manifest('story', 'lin', request); });
  expect(host.maker).toHaveBeenCalledTimes(1);
  expect(save).toHaveBeenCalledTimes(2);
  expect(host.current().pictureOf('story', 'lin')).not.toBe(previous);
});
